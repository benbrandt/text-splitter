"""Regenerate the shipped stubs from Rust, or check that they are current."""

import argparse
import difflib
import os
import subprocess
import sys
import sysconfig
import tempfile
import zipfile
from importlib.metadata import version
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of updating")
    args = parser.parse_args()
    project = Path(__file__).resolve().parents[1]

    # Introspection output depends on the generator as well as PyO3. Keep this
    # version in sync with requirements-typing.txt when deliberately regenerating.
    if version("maturin") != "1.15.0" or version("pyo3-introspection") != "0.30.1":
        parser.error("install the pinned generators from requirements-typing.txt")

    target = project.parents[1] / "target"
    target.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir=target, prefix="stubs-") as output:
        subprocess.run(
            [
                sys.executable,
                "-m",
                "maturin",
                "build",
                "--locked",
                "--features",
                "stubgen",
                "--out",
                output,
            ],
            cwd=project,
            check=True,
        )
        # Maturin 1.15 embeds the older 0.29 introspector. Use PyO3's matching
        # standalone tool so new metadata (such as __all__) isn't discarded.
        (wheel,) = Path(output).glob("*.whl")
        with zipfile.ZipFile(wheel) as archive:
            (member,) = (
                name for name in archive.namelist() if name.endswith((".so", ".pyd"))
            )
            binary = Path(output, Path(member).name)
            binary.write_bytes(archive.read(member))
        introspector = Path(sysconfig.get_path("scripts")) / (
            "pyo3-introspection.exe" if os.name == "nt" else "pyo3-introspection"
        )
        subprocess.run(
            [str(introspector), str(binary), "semantic_text_splitter", output],
            check=True,
        )
        generated = Path(output, "__init__.pyi").read_text(encoding="utf-8")

    # Only normalize whitespace; signatures and docs come entirely from Rust.
    content = "# Generated by scripts/generate_stubs.py; do not edit.\n"
    content += (
        "\n".join(line.rstrip() for line in generated.splitlines()).rstrip() + "\n"
    )
    stub = project / "semantic_text_splitter.pyi"
    if args.check:
        current = stub.read_text(encoding="utf-8")
        if current != content:
            sys.stderr.writelines(
                difflib.unified_diff(
                    current.splitlines(keepends=True),
                    content.splitlines(keepends=True),
                    fromfile=str(stub),
                    tofile="generated",
                )
            )
            print(
                "Run python scripts/generate_stubs.py to update the stubs.",
                file=sys.stderr,
            )
            return 1
    else:
        stub.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
